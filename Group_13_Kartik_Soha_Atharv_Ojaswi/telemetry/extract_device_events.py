#!/usr/bin/env python3
"""
extract_device_events.py
========================

REAL on-device event extractor for the BoardroomXR project report.

*** THIS SCRIPT PRODUCES REAL MEASURED DATA, NOT SIMULATED DATA. ***

It parses an `adb logcat` capture taken from the Meta Quest during the
single-headset test run and emits one row per security-relevant event, with
both clocks the build writes (the Android logcat wall clock and the
SessionLogger UTC stamp / monotonic `t=` session clock).

Nothing is inferred, averaged or sampled: every row quotes the log line it came
from verbatim in `source_log_text`, together with its 1-based line number in the
source capture, so each figure in the report can be traced back to the device.
The only rows not lifted verbatim are the two derived ones, both marked as such
in `category`:

    gesture_stage_stalled   the point in each MFA session after which no further
                            gesture stroke was accepted, up to the timeout
    otp_result              recorded as "not_reached", because the capture
                            contains no OTP verification event at all

Output (default: Tools/real_device_data/)
-----------------------------------------
    device_test_events.csv   one row per extracted event, data_source=real_device

This data is kept strictly separate from the synthetic dataset in
Tools/synthetic_data/, which is generated by generate_synthetic_participants.py
and must never be combined with it.

Reading the CSV back:
    pd.read_csv(path, comment="#")

Requires: pandas.
Usage:    python Tools/extract_device_events.py [--log PATH] [--outdir DIR]
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

import pandas as pd

REAL_TAG = "real_device"

DEFAULT_LOG = Path(r"C:\Users\HP\launch_log.txt")

# --------------------------------------------------------------------------- #
# Log line grammar
# --------------------------------------------------------------------------- #

# 09-30 16:33:48.748  4696  4831 I Unity   : <message>
LOGCAT_RE = re.compile(
    r"^(?P<stamp>\d{2}-\d{2} \d{2}:\d{2}:\d{2}\.\d{3})\s+\d+\s+\d+\s+"
    r"[VDIWEF] Unity\s*:\s(?P<msg>.*)$"
)

# [2026-09-30 11:03:48.747Z] [t=4.894] <text>     (BoardroomXR.Logging.SessionLogger)
SESSION_RE = re.compile(
    r"^\[(?P<utc>\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}\.\d{3})Z\]\s"
    r"\[t=(?P<t>\d+\.\d+)\]\s(?P<text>.*)$"
)

GESTURE_SUBMITTED_RE = re.compile(
    r"^Gesture stroke submitted: (?P<points>\d+) points over (?P<secs>\d+\.\d+)s\."
)
GESTURE_SCORE_RE = re.compile(
    r"^Factor 2 \(Gesture\) (?P<outcome>\w+) locally: score=(?P<score>\d+\.\d+), "
    r"required>=(?P<threshold>\d+\.\d+)\."
)
GESTURE_DISCARD_RE = re.compile(
    r"^Gesture stroke discarded: (?P<secs>\d+\.\d+)s, (?P<points>\d+) points "
    r"\(need >=(?P<min_secs>\d+\.\d+)s and >=(?P<min_points>\d+) points\)\."
)
PIN_SERVER_RE = re.compile(
    r"^\[server\] PIN check for (?P<identity>\S+): (?P<outcome>\w+)\."
)
AVATAR_RE = re.compile(
    r"^Registered avatar\s*(?P<identity>\S*)\s*\(client (?P<client>\d+)\)\. "
    r"Verified=(?P<verified>\w+)\."
)
TEMPLATE_RE = re.compile(
    r"^Loaded enrolled gesture template for (?P<identity>\S+) "
    r"\((?P<points>\d+) points\)\."
)
TIMEOUT_RE = re.compile(
    r"^MFA session TIMED OUT after (?P<limit>\d+)s at stage (?P<stage>\w+)\."
)

# Gesture-stage events that count as the stage still registering input.
GESTURE_INPUT_PREFIXES = (
    "Gesture stroke started",
    "Gesture stroke submitted",
    "Gesture stroke discarded",
    "Factor 2 (Gesture)",
)


# --------------------------------------------------------------------------- #
# Parsing
# --------------------------------------------------------------------------- #

def read_log(path):
    """Yield (line_no, logcat_stamp, utc, t_seconds, message) for Unity lines."""
    with open(path, "r", encoding="utf-8", errors="replace") as fh:
        for line_no, raw in enumerate(fh, start=1):
            m = LOGCAT_RE.match(raw.rstrip("\n"))
            if not m:
                continue
            msg = m.group("msg").strip()
            if not msg:
                continue
            sm = SESSION_RE.match(msg)
            if sm:
                yield (line_no, m.group("stamp"),
                       sm.group("utc").replace(" ", "T") + "Z",
                       float(sm.group("t")), sm.group("text"))
            else:
                yield (line_no, m.group("stamp"), "", None, msg)


def extract(log_path):
    """Build the ordered event list from one logcat capture."""
    events = []
    session = 0                 # MFA session index; 0 = before the first session
    stage = "pre_session"
    pending_stroke = None       # the "stroke submitted" line a score belongs to
    ignored_in_gesture = []     # t= of keypad presses swallowed by the gesture stage
    last_gesture_input = None   # last gesture event seen in this session

    def add(category, detail, line_no, stamp, utc, t, text,
            score="", threshold="", result="", stage_override=None):
        events.append({
            "event_index": len(events) + 1,
            "log_timestamp": stamp,
            "session_clock_utc": utc,
            "t_seconds": "" if t is None else round(t, 3),
            "mfa_session": session if session else "",
            "category": category,
            "stage": stage if stage_override is None else stage_override,
            "detail": detail,
            "score": score,
            "threshold": threshold,
            "result": result,
            "log_line": line_no,
            "source_log_text": text,
            "data_source": REAL_TAG,
        })

    def close_gesture_stall(line_no, stamp, utc, t, text, limit, timed_out_stage):
        """Derived row: where the gesture stage stopped responding."""
        if last_gesture_input is None:
            return
        g_t, g_stamp, g_text = last_gesture_input
        silent = None if t is None else t - g_t
        after = sum(1 for pt in ignored_in_gesture if pt is not None and pt > g_t)
        detail = (
            f"last gesture input registered at t={g_t:.3f} ({g_stamp}): "
            f"{g_text} No further stroke was captured after this point; the "
            f"only remaining input the stage logged was {after} ignored keypad "
            f"press(es) ({len(ignored_in_gesture)} ignored across the whole "
            f"gesture stage)"
            + ("" if silent is None
               else f"; {silent:.1f}s of no gesture progress before the "
                    f"{limit}s session timeout")
            + "."
        )
        events.append({
            "event_index": len(events) + 1,
            "log_timestamp": stamp,
            "session_clock_utc": utc,
            "t_seconds": "" if t is None else round(t, 3),
            "mfa_session": session if session else "",
            "category": "gesture_stage_stalled",
            "stage": "Gesture",
            "detail": detail,
            "score": "",
            "threshold": "",
            "result": "stopped_responding",
            "log_line": line_no,
            "source_log_text": f"[derived] last gesture input: {g_text}",
            "data_source": REAL_TAG,
        })
        events.append({
            "event_index": len(events) + 1,
            "log_timestamp": stamp,
            "session_clock_utc": utc,
            "t_seconds": "" if t is None else round(t, 3),
            "mfa_session": session if session else "",
            "category": "otp_result",
            "stage": timed_out_stage,
            "detail": "no OTP verification event in the capture; Factor 2 "
                      "(gesture) never cleared the 0.750 threshold, so Factor 3 "
                      "(rotating OTP) was never entered in this session.",
            "score": "",
            "threshold": "",
            "result": "not_reached",
            "log_line": line_no,
            "source_log_text": "[derived] absence of any OTP verification line",
            "data_source": REAL_TAG,
        })

    for line_no, stamp, utc, t, text in read_log(log_path):

        # ---- networking / gate / identity bring-up ------------------------ #
        if text.startswith("Host-local gated content HIDDEN"):
            add("gate_hide", "boardroom content hidden locally before "
                             "networking started", line_no, stamp, utc, t, text,
                result="hidden")
            continue

        if text.startswith("BoardroomAccessGate active (server)"):
            add("gate_active", "access gate live on the host and still gating "
                                "the boardroom content", line_no, stamp, utc, t,
                text, result="gating")
            continue

        m = AVATAR_RE.match(text)
        if m:
            ident = m.group("identity") or "(empty claimed id)"
            add("avatar_registration",
                f"avatar registered for client {m.group('client')} as {ident}, "
                f"verified={m.group('verified')}",
                line_no, stamp, utc, t, text,
                result=f"verified={m.group('verified')}")
            continue

        if text.startswith("AvatarIdentity spawned."):
            add("avatar_registration", "AvatarIdentity network object spawned "
                                       "on the host", line_no, stamp, utc, t,
                text, result="spawned")
            continue

        if text.startswith("SpoofDetector active (server)"):
            add("spoof_detector_active",
                "anti-spoofing monitor armed for the registered avatar",
                line_no, stamp, utc, t, text, result="armed")
            continue

        if text.startswith("[server] Credentials provisioned:"):
            add("credential_provisioning",
                "PIN hash, TOTP parameters and gesture threshold provisioned "
                "on the host", line_no, stamp, utc, t, text,
                threshold="0.75", result="provisioned")
            continue

        if text.startswith("[NetworkHostBootstrap] StartHost()"):
            result = text.rsplit("->", 1)[-1].strip().rstrip(".")
            add("start_host", "Netcode host start requested by the bootstrap",
                line_no, stamp, utc, t, text, result=result)
            continue

        # ---- MFA session lifecycle ---------------------------------------- #
        if text == "MFA session started.":
            session += 1
            stage = "Pin"
            pending_stroke = None
            ignored_in_gesture = []
            last_gesture_input = None
            add("session_lifecycle", "MFA session opened at the PIN factor",
                line_no, stamp, utc, t, text, result="started")
            continue

        m = TIMEOUT_RE.match(text)
        if m:
            close_gesture_stall(line_no, stamp, utc, t, text,
                                m.group("limit"), m.group("stage"))
            stage = m.group("stage")
            add("session_lifecycle",
                f"session abandoned by the {m.group('limit')}s timeout without "
                f"completing the three factors",
                line_no, stamp, utc, t, text, result="timed_out")
            last_gesture_input = None
            continue

        # ---- Factor 1, PIN ------------------------------------------------ #
        m = PIN_SERVER_RE.match(text)
        if m:
            add("pin_result",
                f"server-side PIN verification for {m.group('identity')}",
                line_no, stamp, utc, t, text, result=m.group("outcome"))
            continue

        if text.startswith("Factor 1 (PIN)"):
            outcome = "passed" if "passed" in text else "failed"
            add("pin_result", "client advanced past the PIN factor",
                line_no, stamp, utc, t, text, result=outcome)
            continue

        # ---- Factor 2, gesture -------------------------------------------- #
        m = TEMPLATE_RE.match(text)
        if m:
            stage = "Gesture"
            add("gesture_template_loaded",
                f"enrolled template for {m.group('identity')} loaded, "
                f"{m.group('points')} points",
                line_no, stamp, utc, t, text, result="loaded")
            continue

        m = GESTURE_SUBMITTED_RE.match(text)
        if m:
            pending_stroke = (m.group("points"), m.group("secs"))
            last_gesture_input = (t, stamp, text)
            continue

        m = GESTURE_SCORE_RE.match(text)
        if m:
            if pending_stroke:
                shape = (f"stroke of {pending_stroke[0]} points over "
                         f"{pending_stroke[1]}s")
            else:
                shape = "stroke shape not logged"
            score = float(m.group("score"))
            threshold = float(m.group("threshold"))
            passed = score >= threshold
            add("gesture_score",
                f"{shape} scored against the enrolled template; "
                f"{score:.3f} {'>=' if passed else '<'} {threshold:.3f}",
                line_no, stamp, utc, t, text,
                score=f"{score:.3f}", threshold=f"{threshold:.3f}",
                result="pass" if passed else "fail")
            pending_stroke = None
            last_gesture_input = (t, stamp, text)
            continue

        m = GESTURE_DISCARD_RE.match(text)
        if m:
            add("gesture_stroke_discarded",
                f"stroke rejected before scoring: {m.group('secs')}s and "
                f"{m.group('points')} points, below the "
                f"{m.group('min_secs')}s / {m.group('min_points')}-point "
                f"capture minimum",
                line_no, stamp, utc, t, text, result="discarded")
            last_gesture_input = (t, stamp, text)
            continue

        if text.startswith("Gesture stroke started"):
            last_gesture_input = (t, stamp, text)
            continue

        # ---- stage-mismatched input (counted, not emitted) ---------------- #
        if text.startswith("Keypad press ignored: stage is Gesture"):
            ignored_in_gesture.append(t)
            continue

    return pd.DataFrame(events)


# --------------------------------------------------------------------------- #
# Output
# --------------------------------------------------------------------------- #

def header_comment(log_path):
    return (f"# REAL DEVICE DATA - extracted by extract_device_events.py from "
            f"{Path(log_path).name} (adb logcat, Meta Quest). Measured, not "
            f"simulated. Do not combine with Tools/synthetic_data/.")


def write_csv(df, path, log_path):
    with open(path, "w", newline="", encoding="utf-8") as fh:
        fh.write(header_comment(log_path) + "\n")
        df.to_csv(fh, index=False, lineterminator="\n")
    return path


def main():
    ap = argparse.ArgumentParser(
        description="Extract the real on-device MFA event table from an adb "
                    "logcat capture of the BoardroomXR Quest test run.")
    ap.add_argument("--log", type=Path, default=DEFAULT_LOG,
                    help=f"logcat capture to parse (default {DEFAULT_LOG})")
    ap.add_argument("--outdir", type=Path,
                    default=Path(__file__).resolve().parent / "real_device_data",
                    help="output directory")
    args = ap.parse_args()

    if not args.log.is_file():
        raise SystemExit(f"log not found: {args.log}")

    args.outdir.mkdir(parents=True, exist_ok=True)
    events = extract(args.log)
    out = write_csv(events, args.outdir / "device_test_events.csv", args.log)

    banner = header_comment(args.log)
    print("=" * 78)
    print(banner)
    print(f"{len(events)} events extracted from {args.log}")
    print("=" * 78)

    print("\nEVENTS BY CATEGORY (real device data)\n")
    print(events.category.value_counts().to_string())

    scores = events[events.category == "gesture_score"]
    if not scores.empty:
        s = scores.score.astype(float)
        print(f"\n{len(s)} gesture scores: min {s.min():.3f}, max {s.max():.3f}, "
              f"mean {s.mean():.3f}; "
              f"{(scores.result == 'pass').sum()} passed, "
              f"{(scores.result == 'fail').sum()} failed")

    print("\nWritten to " + str(out))


if __name__ == "__main__":
    main()
